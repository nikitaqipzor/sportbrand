import * as Crypto from "expo-crypto";

/**
 * Идентификатор тренировки рождается на устройстве, а не на сервере.
 *
 * Это то, что делает тренировку офлайн возможной: в зале без связи приложение
 * должно начать сессию и с первого же подхода знать, к чему их привязывать.
 * Сервер принимает такой id и делает создание идемпотентным — тот же принцип,
 * по которому каждый подход несёт свой clientMutationId (ADR 0002).
 *
 * UUID v4 из криптографического источника: столкновение идентификаторов
 * означало бы, что чужая тренировка получила бы 409 при создании, поэтому
 * Math.random здесь неуместен.
 */
export function newWorkoutId(): string {
  return Crypto.randomUUID();
}
